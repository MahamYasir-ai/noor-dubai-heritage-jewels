export const formatCurrencyPrice = (priceAED: number, currency: string, isAr: boolean = false): string => {
  const curr = CURRENCY_RATES[currency] || CURRENCY_RATES['AED'];
  const converted = Math.round(priceAED * curr.rate);
  const sym = isAr ? curr.symbolAr : curr.symbol;
  return `${sym} ${converted.toLocaleString()}`;
};

